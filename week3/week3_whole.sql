-- 1. 핵심 비지니스 KPI 요약 추출
-- 전체 기간의 총 가입자 수, 완료 주문(COMPLETED) 건수,
-- 구매자 수(PU), 총 매출(GMV), ARPU, ARPPU를 구하기
-- ARPU : 일정 기간 동안 전체 사용자 1인당 발생한 평균 매출 (결제 여부 관계 X, 전체유저 분모로 사용)
-- ARPPU : 일정 기간 동안 전체 사용자 1인당 발생한 평균 매출 (결제 유저만 분모로 사용)

SELECT
	COUNT(DISTINCT U.USER_ID) AS COUNT_USER,
    COUNT(DISTINCT CASE WHEN O.ORDER_STATUS = 'COMPLETED' THEN O.ORDER_ID END)
    AS COUNT_ORDER_COMPLETED,
    COUNT(DISTINCT CASE WHEN O.ORDER_STATUS = 'COMPLETED' THEN O.USER_ID END)
    AS COMPLETED_ORDER_USERS,
    COALESCE(SUM(CASE WHEN O.ORDER_STATUS = 'COMPLETED' THEN O.TOTAL_AMOUNT END), 0) AS REVENUE_AMOUN,
    round(
    SUM(CASE WHEN O.ORDER_STATUS = 'COMPLETED' THEN O.TOTAL_AMOUNT END)
    /
    NULLIF(COUNT(DISTINCT u.user_id), 0)
    , 2)
    AS ARPU,
    round(
    SUM(CASE WHEN O.ORDER_STATUS = 'COMPLETED' THEN O.TOTAL_AMOUNT END)
    /
    NULLIF(COUNT(DISTINCT CASE WHEN O.ORDER_STATUS = 'COMPLETED' THEN u.user_id END), 0)
    , 2)
    as ARPPU
FROM USERS AS U
LEFT JOIN ORDERS AS O
	ON U.USER_ID = O.USER_ID;

